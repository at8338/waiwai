import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { SpaceStore } from './spaces.ts';
import { WorldPolicyStore } from './world-policy.ts';
const admin = { name: '管理者', accountId: 'slack:TADMIN:UADMIN' };
const a = { id: 'slack:TTEAM:UALPHA', name: 'A' }, b = { id: 'slack:TTEAM:UBETA', name: 'B' };
test('server registry migrates legacy members once, persists assignments and never auto-enrolls new users', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'waiwai-spaces-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'spaces.json'), authority = new WorldPolicyStore(undefined, admin.accountId);
  const registry = new SpaceStore(file, authority, [a]);
  assert.equal(registry.allowed('default', { name: a.name, accountId: a.id }), true);
  assert.equal(registry.allowed('default', { name: b.name, accountId: b.id }), false);
  await registry.apply({ type: 'create', revision: 0, name: 'チームB' }, admin, [a, b]);
  const id = registry.all()[1].id;
  await registry.apply({ type: 'membership', revision: 1, accountId: b.id, spaceIds: [id] }, admin, [a, b]);
  const restored = new SpaceStore(file, authority, [a, b]);
  assert.equal(restored.allowed('default', { name: b.name, accountId: b.id }), false);
  assert.equal(restored.allowed(id, { name: b.name, accountId: b.id }), true);
  assert.equal(restored.allowed(id, { name: a.name, accountId: a.id }), false);
  assert.equal(restored.allowed(id, undefined, true), false);
  assert.equal(restored.allowed('default', undefined, true), true);
  assert.deepEqual(restored.snapshot({ accountId: b.id, name: 'B' }, [a, b]).spaces.map(s => s.id), [id]);
  assert.equal(restored.snapshot({ accountId: b.id, name: 'B' }, [a, b]).members, undefined);
});
test('membership writes require immutable administrator identity, detect conflicts, and keep multiple memberships', async () => {
  const store = new SpaceStore(undefined, new WorldPolicyStore(undefined, admin.accountId), [a]);
  const impostor = { accountId: a.id, name: 'tt-asahara', email: 'tt-asahara@kddi.com', emailVerified: true };
  await assert.rejects(store.apply({ type: 'create', revision: 0, name: '禁止' }, impostor, [a]), /管理者/);
  await store.apply({ type: 'create', revision: 0, name: '追加' }, admin, [a]);
  const id = store.all()[1].id;
  await assert.rejects(store.apply({ type: 'membership', revision: 0, accountId: a.id, spaceIds: [] }, admin, [a]), /更新/);
  await store.apply({ type: 'membership', revision: 1, accountId: a.id, spaceIds: ['default', id] }, admin, [a]);
  assert.equal(store.snapshot({ name: a.name, accountId: a.id }, [a]).spaces.length, 2);
  await assert.rejects(store.apply({ type: 'membership', revision: 2, accountId: b.id, spaceIds: [id] }, admin, [a]), /ログイン済み/);
  await assert.rejects(store.apply({ type: 'update', revision: 2, id, enabled: false, name: '../escape' }, admin, [a], () => false), /管理者/);
  await store.apply({ type: 'update', revision: 2, id, enabled: false, name: 'お休み' }, admin, [a]);
  assert.equal(store.allowed(id, admin), false);
  await assert.rejects(store.apply({ type: 'update', revision: 3, id: 'default', enabled: false, name: 'Waiwai' }, admin, [a]), /少なくとも/);
});
test('a failed or corrupt registry never silently removes membership restrictions', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'waiwai-space-bad-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'registry.json'); await writeFile(file, '{broken');
  const authority = new WorldPolicyStore(undefined, admin.accountId);
  assert.throws(() => new SpaceStore(file, authority), /restore/);
  const store = new SpaceStore(undefined, authority);
  await assert.rejects(store.apply({ type: 'create', name: '\n', revision: 0 }, admin, []));
  assert.equal(store.all().length, 1);
});
test('disk save failures preserve the previous assignments and revision', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'waiwai-space-write-')); t.after(() => rm(dir, { recursive: true, force: true }));
  const file = join(dir, 'registry.json'), store = new SpaceStore(file, new WorldPolicyStore(undefined, admin.accountId), [a]);
  await rm(file); await mkdir(file);
  await assert.rejects(store.apply({ type: 'membership', accountId: a.id, spaceIds: [], revision: 0 }, admin, [a]));
  assert.equal(store.allowed('default', { accountId: a.id, name: a.name }), true);
  assert.equal(store.snapshot(admin, [a]).revision, 0);
});
